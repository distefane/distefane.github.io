/* =====================================================
   LEER INPUTS TEMPORIZADOR
===================================================== */

function obtenerDuracionInputs() {

    const horas =
        Math.max(
            0,
            Number(
                countdownHours.value
            ) || 0
        );


    const minutos =
        Math.min(
            59,
            Math.max(
                0,
                Number(
                    countdownMinutes.value
                ) || 0
            )
        );


    const segundos =
        Math.min(
            59,
            Math.max(
                0,
                Number(
                    countdownSeconds.value
                ) || 0
            )
        );


    return (
        horas * 3600000 +
        minutos * 60000 +
        segundos * 1000
    );

}



/* =====================================================
   ACTUALIZAR INPUTS DESDE DURACIÓN
===================================================== */

function cargarDuracionEnInputs(ms) {

    const totalSegundos =
        Math.floor(
            ms / 1000
        );


    const horas =
        Math.floor(
            totalSegundos /
            3600
        );


    const minutos =
        Math.floor(
            (
                totalSegundos %
                3600
            ) /
            60
        );


    const segundos =
        totalSegundos %
        60;


    countdownHours.value =
        horas;


    countdownMinutes.value =
        minutos;


    countdownSeconds.value =
        segundos;

}



/* =====================================================
   FORMATEAR CUENTA REGRESIVA
===================================================== */

function formatearCountdown(ms) {

    const segundosTotales =
        Math.max(
            0,
            Math.ceil(
                ms / 1000
            )
        );


    const horas =
        Math.floor(
            segundosTotales /
            3600
        );


    const minutos =
        Math.floor(
            (
                segundosTotales %
                3600
            ) /
            60
        );


    const segundos =
        segundosTotales %
        60;


    return [
        horas,
        minutos,
        segundos
    ]
        .map(
            numero =>
                String(numero)
                    .padStart(
                        2,
                        "0"
                    )
        )
        .join(":");

}



/* =====================================================
   OBTENER TIEMPO RESTANTE REAL
===================================================== */

function obtenerTiempoRestante() {

    if (
        temporizador.activo &&
        temporizador.fin
    ) {

        return Math.max(
            0,
            temporizador.fin -
            Date.now()
        );

    }


    return Math.max(
        0,
        temporizador.tiempoRestante
    );

}



/* =====================================================
   INICIAR / PAUSAR TEMPORIZADOR
===================================================== */

function alternarTemporizador() {

    prepararAudio();


    if (temporizador.activo) {

        pausarTemporizador();

    } else {

        iniciarTemporizador();

    }

}


function iniciarTemporizador() {

    let tiempo;


    if (
        temporizador.finalizado ||
        temporizador.tiempoRestante <= 0
    ) {

        tiempo =
            obtenerDuracionInputs();


        if (tiempo <= 0) {

            alert(
                t("invalidCountdown")
            );

            return;

        }


        temporizador.duracionInicial =
            tiempo;


        temporizador.tiempoRestante =
            tiempo;


        temporizador.finalizado =
            false;

    } else {

        /*
            Si nunca se ha iniciado o fue
            reiniciado, tomamos el valor
            actual de los inputs.
        */

        if (
            !temporizador.fin &&
            !temporizador.activo
        ) {

            const inputTiempo =
                obtenerDuracionInputs();


            if (
                inputTiempo !==
                temporizador.tiempoRestante
            ) {

                if (
                    inputTiempo <= 0
                ) {

                    alert(
                        t(
                            "invalidCountdown"
                        )
                    );

                    return;

                }


                temporizador
                    .duracionInicial =
                    inputTiempo;


                temporizador
                    .tiempoRestante =
                    inputTiempo;

            }

        }

    }


    if (
        temporizador
            .tiempoRestante <= 0
    ) {

        alert(
            t("invalidCountdown")
        );

        return;

    }


    temporizador.activo =
        true;


    temporizador.finalizado =
        false;


    temporizador.fin =
        Date.now() +
        temporizador
            .tiempoRestante;


    bloquearInputsTemporizador(
        true
    );


    guardarTemporizador();

    actualizarEstadoTemporizador();

}



/* =====================================================
   PAUSAR TEMPORIZADOR
===================================================== */

function pausarTemporizador() {

    temporizador.tiempoRestante =
        obtenerTiempoRestante();


    temporizador.activo =
        false;


    temporizador.fin =
        null;


    bloquearInputsTemporizador(
        false
    );


    guardarTemporizador();

    actualizarEstadoTemporizador();

}



/* =====================================================
   REINICIAR TEMPORIZADOR
===================================================== */

function reiniciarTemporizador() {

    temporizador.activo =
        false;


    temporizador.finalizado =
        false;


    temporizador.fin =
        null;


    temporizador.tiempoRestante =
        temporizador
            .duracionInicial;


    cargarDuracionEnInputs(
        temporizador
            .duracionInicial
    );


    bloquearInputsTemporizador(
        false
    );


    countdownDisplay
        .classList.remove(
            "finished"
        );


    guardarTemporizador();

    actualizarEstadoTemporizador();

}



/* =====================================================
   FINALIZAR TEMPORIZADOR
===================================================== */

function finalizarTemporizador() {

    if (
        temporizador.finalizado
    ) {

        return;

    }


    temporizador.activo =
        false;


    temporizador.finalizado =
        true;


    temporizador.fin =
        null;


    temporizador.tiempoRestante =
        0;


    guardarTemporizador();


    bloquearInputsTemporizador(
        false
    );


    countdownDisplay.textContent =
        "00:00:00";


    countdownDisplay
        .classList.add(
            "finished"
        );


    actualizarEstadoTemporizador();


    reproducirAlarma();

}



