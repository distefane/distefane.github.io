/* =====================================================
   INICIAR CRONÓMETRO
===================================================== */

function iniciar(id) {

    const timer =
        cronometros.find(
            timer =>
                timer.id === id
        );


    if (
        !timer ||
        timer.activo
    ) {

        return;

    }


    timer.activo =
        true;


    timer.inicio =
        Date.now();


    guardarDatos();

    renderizar();

}



/* =====================================================
   PAUSAR CRONÓMETRO
===================================================== */

function pausar(id) {

    const timer =
        cronometros.find(
            timer =>
                timer.id === id
        );


    if (
        !timer ||
        !timer.activo
    ) {

        return;

    }


    const ahora =
        Date.now();


    timer.tiempoAcumulado +=
        ahora -
        timer.inicio;


    timer.activo =
        false;


    timer.inicio =
        null;


    guardarDatos();

    renderizar();

}



/* =====================================================
   REINICIAR CRONÓMETRO
===================================================== */

function reiniciar(id) {

    const timer =
        cronometros.find(
            timer =>
                timer.id === id
        );


    if (!timer) {

        return;

    }


    timer.tiempoAcumulado =
        0;


    if (timer.activo) {

        timer.inicio =
            Date.now();

    }


    guardarDatos();

    renderizar();

}



/* =====================================================
   ELIMINAR CRONÓMETRO
===================================================== */

function eliminar(id) {

    const timer =
        cronometros.find(
            timer =>
                timer.id === id
        );


    if (!timer) {

        return;

    }


    const confirmar =
        window.confirm(
            t(
                "deleteConfirm"
            )(
                timer.nombre
            )
        );


    if (!confirmar) {

        return;

    }


    cronometros =
        cronometros.filter(
            timer =>
                timer.id !== id
        );


    guardarDatos();

    renderizar();

}



/* =====================================================
   EDITAR CRONÓMETRO
===================================================== */

function editar(id) {

    const timer =
        cronometros.find(
            timer =>
                timer.id === id
        );


    if (!timer) {

        return;

    }


    editandoId =
        id;


    inputNombre.value =
        timer.nombre;


    modalTitulo.textContent =
        t(
            "editTimerTitle"
        );


    abrirModal();


    inputNombre.focus();

}



/* =====================================================
   CALCULAR TIEMPO CRONÓMETRO
===================================================== */

function obtenerTiempo(timer) {

    let tiempo =
        timer.tiempoAcumulado;


    if (
        timer.activo &&
        timer.inicio
    ) {

        tiempo +=
            Date.now() -
            timer.inicio;

    }


    return tiempo;

}



/* =====================================================
   FORMATEAR TIEMPO
===================================================== */

function formatearTiempo(ms) {

    const segundosTotales =
        Math.floor(
            ms / 1000
        );


    const horas =
        Math.floor(
            segundosTotales /
            3600
        );


    const minutos =
        Math.floor(
            (
                segundosTotales %
                3600
            ) /
            60
        );


    const segundos =
        segundosTotales %
        60;


    return [
        horas,
        minutos,
        segundos
    ]
        .map(
            numero =>
                String(numero)
                    .padStart(
                        2,
                        "0"
                    )
        )
        .join(":");

}



/* =====================================================
   RENDERIZAR CRONÓMETROS
===================================================== */

function renderizar() {

    contenedor.innerHTML =
        "";


    if (
        cronometros.length === 0
    ) {

        emptyState.style.display =
            "block";

        return;

    }


    emptyState.style.display =
        "none";


    cronometros.forEach(
        timer => {

            const tarjeta =
                document.createElement(
                    "article"
                );


            tarjeta.className =
                "timer-card";


            tarjeta.innerHTML = `

                <div class="timer-info">

                    <h2>
                        ${escaparHTML(
                            timer.nombre
                        )}
                    </h2>

                    <p
                        class="estado ${
                            timer.activo
                                ? "activo"
                                : ""
                        }"
                    >

                        ${
                            timer.activo
                                ? t(
                                    "running"
                                )
                                : t(
                                    "paused"
                                )
                        }

                    </p>

                </div>


                <div
                    class="timer-time"
                    data-timer="${timer.id}"
                >

                    ${formatearTiempo(
                        obtenerTiempo(
                            timer
                        )
                    )}

                </div>


                <div class="timer-actions">

                    ${
                        timer.activo

                        ? `

                            <button
                                class="btn-pause"
                                onclick="pausar(${timer.id})"
                            >
                                ${t("pause")}
                            </button>

                        `

                        : `

                            <button
                                class="btn-start"
                                onclick="iniciar(${timer.id})"
                            >
                                ${t("start")}
                            </button>

                        `
                    }


                    <button
                        class="btn-secondary"
                        onclick="reiniciar(${timer.id})"
                    >
                        ${t("reset")}
                    </button>


                    <button
                        class="btn-edit"
                        onclick="editar(${timer.id})"
                    >
                        ${t("edit")}
                    </button>


                    <button
                        class="btn-danger"
                        onclick="eliminar(${timer.id})"
                    >
                        ${t("delete")}
                    </button>

                </div>

            `;


            contenedor.appendChild(
                tarjeta
            );

        }
    );

}



/* =====================================================
   ACTUALIZAR CRONÓMETROS EN VIVO
===================================================== */

function actualizarTiempos() {

    cronometros.forEach(
        timer => {

            if (
                !timer.activo
            ) {

                return;

            }


            const elemento =
                document.querySelector(
                    `[data-timer="${timer.id}"]`
                );


            if (elemento) {

                elemento.textContent =
                    formatearTiempo(
                        obtenerTiempo(
                            timer
                        )
                    );

            }

        }
    );

}



