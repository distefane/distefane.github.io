/* =====================================================
   ESTADO VISUAL TEMPORIZADOR
===================================================== */

function actualizarEstadoTemporizador() {

    const restante =
        obtenerTiempoRestante();


    countdownDisplay.textContent =
        formatearCountdown(
            restante
        );


    countdownStatus.className =
        "countdown-status";


    if (
        temporizador.finalizado
    ) {

        countdownStatus
            .textContent =
            t(
                "countdownFinished"
            );


        countdownStatus
            .classList.add(
                "finished"
            );


        countdownStart
            .textContent =
            t("start");


        return;

    }


    if (
        temporizador.activo
    ) {

        countdownStatus
            .textContent =
            t(
                "countdownRunning"
            );


        countdownStatus
            .classList.add(
                "running"
            );


        countdownStart
            .textContent =
            t("pause");


        return;

    }


    if (
        temporizador
            .tiempoRestante <
        temporizador
            .duracionInicial
    ) {

        countdownStatus
            .textContent =
            t(
                "countdownPaused"
            );


        countdownStart
            .textContent =
            t("start");


        return;

    }


    countdownStatus
        .textContent =
        t(
            "countdownReady"
        );


    countdownStart
        .textContent =
        t("start");

}



/* =====================================================
   ACTUALIZAR TEMPORIZADOR EN VIVO
===================================================== */

function actualizarCountdown() {

    if (
        !temporizador.activo
    ) {

        return;

    }


    const restante =
        obtenerTiempoRestante();


    countdownDisplay.textContent =
        formatearCountdown(
            restante
        );


    if (
        restante <= 0
    ) {

        finalizarTemporizador();

    }

}



/* =====================================================
   RECUPERAR TEMPORIZADOR AL RECARGAR
===================================================== */

function recuperarTemporizador() {

    /*
        Si estaba activo antes de
        recargar, calculamos cuánto
        tiempo realmente queda.
    */

    if (
        temporizador.activo &&
        temporizador.fin
    ) {

        const restante =
            temporizador.fin -
            Date.now();


        if (
            restante <= 0
        ) {

            temporizador.activo =
                false;


            temporizador.finalizado =
                true;


            temporizador.tiempoRestante =
                0;


            temporizador.fin =
                null;


            guardarTemporizador();

        } else {

            temporizador
                .tiempoRestante =
                restante;

        }

    }


    cargarDuracionEnInputs(
        temporizador
            .duracionInicial
    );


    bloquearInputsTemporizador(
        temporizador.activo
    );


    actualizarEstadoTemporizador();

}



