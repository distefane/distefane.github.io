let audioContext =
    null;


function prepararAudio() {

    try {

        if (!audioContext) {

            audioContext =
                new (
                    window.AudioContext ||
                    window.webkitAudioContext
                )();

        }


        if (
            audioContext.state ===
            "suspended"
        ) {

            audioContext.resume();

        }

    } catch (error) {

        console.log(
            "Audio no disponible:",
            error
        );

    }

}



