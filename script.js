function reproducirTono(
    frecuencia,
    inicio,
    duracion
) {

    const oscillator =
        audioContext
            .createOscillator();


    const gain =
        audioContext
            .createGain();


    oscillator.type =
        "sine";


    oscillator.frequency
        .setValueAtTime(
            frecuencia,
            inicio
        );


    gain.gain
        .setValueAtTime(
            0.0001,
            inicio
        );


    gain.gain
        .exponentialRampToValueAtTime(
            0.07,
            inicio + 0.05
        );


    gain.gain
        .exponentialRampToValueAtTime(
            0.0001,
            inicio + duracion
        );


    oscillator.connect(
        gain
    );


    gain.connect(
        audioContext.destination
    );


    oscillator.start(
        inicio
    );


    oscillator.stop(
        inicio + duracion
    );

}



