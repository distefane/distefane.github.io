/* =====================================================
   GUARDAR CREACIÓN / EDICIÓN
===================================================== */

function guardarModal() {

    const nombre =
        inputNombre
            .value
            .trim();


    if (!nombre) {

        alert(
            t(
                "emptyNameAlert"
            )
        );

        return;

    }


    if (
        editandoId !== null
    ) {

        const timer =
            cronometros.find(
                timer =>
                    timer.id ===
                    editandoId
            );


        if (timer) {

            timer.nombre =
                nombre;


            guardarDatos();

            renderizar();

        }

    } else {

        crearCronometro(
            nombre
        );

    }


    cerrarModal();

}



